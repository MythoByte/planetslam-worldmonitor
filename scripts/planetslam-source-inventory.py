"""Export every upstream host without treating upstream audit status as legal clearance."""
import json
import re
from pathlib import Path

root = Path(__file__).resolve().parent.parent
manifest = json.loads((root / "shared/source-attribution-manifest.json").read_text())
rows = ["# Complete upstream host inventory", "", "Generated by `python3 scripts/planetslam-source-inventory.py`. See API-INVENTORY.md for reviewed provider requirements. Unknown means unverified, not unrestricted. Co-referenced environment names are candidates from source files, not proof that a host requires all of them. No provider is activated by this export.", "", "| Provider / host / category | Authentication | Free / paid | Rate limits | Public redistribution | Self-host availability | Refresh | Environment candidates | Limitations / evidence |", "|---|---|---|---|---|---|---|---|---|"]
for e in manifest["entries"]:
    refs = [r["path"] for r in e.get("references", [])]
    envs = set()
    for ref in refs:
        p = root / ref
        if p.is_file() and p.stat().st_size < 2000000:
            text = p.read_text(errors="replace")
            envs.update(re.findall(r"(?:process\.env\.|import\.meta\.env\.)([A-Z][A-Z0-9_]*)", text))
    envs = sorted(v for v in envs if any(w in v for w in ("KEY", "TOKEN", "PASSWORD", "EMAIL", "URL")))
    fields = [e.get("provider", e["host"]) + " / " + e["host"] + " / " + e["kind"], "Unknown; see provider matrix", "Unknown; no entitlement inferred", "Unknown; cache and honor 429", e.get("license", "Unknown") + "; upstream status: " + e["status"], "Adapter source available; provider service not implied", "See referenced seeder/registry; not verified", ", ".join(envs) or "None observed in referenced files", e.get("attribution", "") + " Sources: " + ", ".join(refs)]
    rows.append("| " + " | ".join(str(x).replace("|", " / ").replace("\n", " ") for x in fields) + " |")
(root / "docs/planetslam/SOURCE-HOSTS.md").write_text("\n".join(rows) + "\n")
print(f"Exported {len(manifest['entries'])} hosts")
